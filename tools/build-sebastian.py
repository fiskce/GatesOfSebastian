#!/usr/bin/env python3
"""Thunder Hunter Sebastian: build Sebastian's sprite sheets from the artwork.

    python3 tools/build-sebastian.py          (needs Pillow)

Reads art/sebastian_idle.gif and art/sebastian_shoot.gif (930x825, transparent,
the feet on the same line in every frame) and writes:

    assets/sebastian/idle.webp, shoot.webp   every frame tightly cropped, packed in rows
    assets/sebastian/splash.webp             the idle loop as an animated WebP for the splash
    js/seb-frames.js                         where each frame sits in its sheet, where it
                                             goes in the 930x825 artwork, and how long it shows

The game draws each frame at its place in the artwork, so the figure never
jitters, whatever the crop. Coordinates in js/seb-frames.js are in artwork
pixels; the sheets are stored at SCALE of that.
"""
import json, os
from PIL import Image, ImageSequence

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SCALE = 0.5            # sheet pixels per artwork pixel
MAX_W = 4096           # widest sheet a phone GPU takes happily
PAD = 2

def frames(name):
    im = Image.open(os.path.join(ROOT, 'art', name))
    out = []
    for f in ImageSequence.Iterator(im):
        out.append((f.convert('RGBA'), f.info.get('duration', 60)))
    return im.size, out

def sheet(clip, name):
    size, fr = frames('sebastian_%s.gif' % clip)
    items = []
    for img, dur in fr:
        bb = img.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        x0, y0, x1, y1 = bb
        x0, y0 = max(0, x0 - 1), max(0, y0 - 1)
        x1, y1 = min(size[0], x1 + 1), min(size[1], y1 + 1)
        crop = img.crop((x0, y0, x1, y1))
        w, h = max(1, round(crop.width * SCALE)), max(1, round(crop.height * SCALE))
        items.append({'img': crop.resize((w, h), Image.LANCZOS), 'ax': x0, 'ay': y0, 'aw': x1 - x0, 'ah': y1 - y0, 'dur': dur})
    # shelf packing, in frame order
    x = y = rowH = 0
    W = 0
    for it in items:
        w, h = it['img'].size
        if x + w + PAD > MAX_W:
            x, y, rowH = 0, y + rowH + PAD, 0
        it['sx'], it['sy'] = x, y
        x += w + PAD; rowH = max(rowH, h); W = max(W, x)
    H = y + rowH
    out = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    for it in items:
        out.paste(it['img'], (it['sx'], it['sy']))
    os.makedirs(os.path.join(ROOT, 'assets', 'sebastian'), exist_ok=True)
    out.save(os.path.join(ROOT, 'assets', 'sebastian', name), 'WEBP', quality=90, method=6)
    meta = [[it['sx'], it['sy'], it['img'].size[0], it['img'].size[1], it['ax'], it['ay'], it['aw'], it['ah'], it['dur']] for it in items]
    print('%s: %d frames, sheet %dx%d, %.1f MB decoded, %d KB file' % (clip, len(items), W, H, W * H * 4 / 1e6,
          os.path.getsize(os.path.join(ROOT, 'assets', 'sebastian', name)) // 1024))
    return size, meta

def splash():
    size, fr = frames('sebastian_idle.gif')
    # crop to the union of the idle frames, 480 px tall
    boxes = [img.getchannel('A').getbbox() for img, _ in fr]
    u = (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))
    k = 480 / (u[3] - u[1])
    imgs = [img.crop(u).resize((round((u[2] - u[0]) * k), 480), Image.LANCZOS) for img, _ in fr]
    imgs[0].save(os.path.join(ROOT, 'assets', 'sebastian', 'splash.webp'), 'WEBP', save_all=True, append_images=imgs[1:],
                 duration=[d for _, d in fr], loop=0, quality=72, method=6)
    print('splash: %d KB' % (os.path.getsize(os.path.join(ROOT, 'assets', 'sebastian', 'splash.webp')) // 1024))

size, idle = sheet('idle', 'idle.webp')
_, shoot = sheet('shoot', 'shoot.webp')
splash()
with open(os.path.join(ROOT, 'js', 'seb-frames.js'), 'w') as f:
    f.write('/* Generated by tools/build-sebastian.py from art/sebastian_*.gif. Do not edit.\n'
            ' * Per frame: [sheet x, sheet y, sheet w, sheet h, art x, art y, art w, art h, ms]. */\n')
    f.write('window.SEB_FRAMES = ' + json.dumps({'art': list(size), 'scale': SCALE, 'idle': idle, 'shoot': shoot}, separators=(',', ':')) + ';\n')
print('wrote js/seb-frames.js')
